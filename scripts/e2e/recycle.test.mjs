import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {launchApp,until} from '../testing/app-session.mjs';

test('Windows Recycle Bin UI uses real owned IDs and preserves user data',{timeout:120000},async t=>{
  const app=await launchApp({emulateFocus:true});
  const invoke=(name,args={})=>app.evaluate(`call(${JSON.stringify(name)},${JSON.stringify(args)})`);
  const directory=fs.realpathSync.native(app.directory),file=path.join(directory,'回收站 QA #.txt');
  fs.writeFileSync(file,'owned-recycle-ui-fixture');
  await invoke('delete_file',{path:file});
  t.after(async()=>{try{const bin=await invoke('recycle_bin_list');const owned=bin.items.filter(e=>e.originalPath.toLowerCase()===file.toLowerCase());if(owned.length)await invoke('recycle_bin_restore',{ids:owned.map(e=>e.id),policy:'keepBoth',operationId:'qa-recycle-cleanup'});}finally{app.close();}});
  await app.click('#sidebar-recycle');
  await until(()=>app.evaluate('!!document.querySelector("#recycle-dialog")&&!recycleState.loading'),'Recycle Bin loaded');
  const bin=await invoke('recycle_bin_list'),owned=bin.items.find(e=>e.originalPath===file);assert.ok(owned,'Owned fixture appears with its real original name');
  await app.evaluate(`recycleSetQuery(${JSON.stringify(path.basename(directory)+' 回收站 QA')});recycleSetSort('name',false);true`);
  assert.equal(await app.evaluate('document.querySelectorAll(".recycle-row").length'),1);
  await app.click(`[data-recycle-id="${owned.id}"]`);
  assert.deepEqual(await app.evaluate('[...recycleState.selected]'),[owned.id]);
  await app.screenshot('recycle-light-zh');
  await app.evaluate("applyTheme('dark',false);true");await app.screenshot('recycle-dark-zh');
  await app.evaluate("applyTheme('light',false);true");
  await app.send('Emulation.setDeviceMetricsOverride',{width:740,height:600,deviceScaleFactor:1,mobile:false});
  assert.equal(await app.evaluate('document.querySelector("#recycle-empty").getBoundingClientRect().right<=innerWidth'),true);
  await app.screenshot('recycle-narrow-zh');await app.send('Emulation.clearDeviceMetricsOverride');
  await app.click('#recycle-remove');
  await until(()=>app.evaluate('!!document.querySelector(".app-confirm-overlay")'),'First permanent-delete confirmation');
  await app.click('.app-confirm-overlay .dialog-actions button:last-child');
  await until(()=>app.evaluate('document.querySelector(".app-confirm-overlay .app-confirm-title")?.textContent.includes("再次")'),'Second permanent-delete confirmation');
  await app.click('.app-confirm-overlay .dialog-actions button:first-child');
  await until(()=>app.evaluate('!recycleState.busy'),'Delete cancelled');
  assert.ok((await invoke('recycle_bin_list')).items.some(e=>e.id===owned.id),'Cancel leaves recycled item intact');
  fs.writeFileSync(file,'new-live-fixture');
  await app.click('#recycle-restore');
  await until(()=>app.evaluate('!recycleState.busy&&!!recycleState.report'),'Restore conflict report');
  assert.equal(await app.evaluate('recycleState.report.skipped[0].code'),'conflict');assert.equal(fs.readFileSync(file,'utf8'),'new-live-fixture');
  await app.click('#recycle-keep');
  await until(()=>app.evaluate('!recycleState.busy&&recycleState.report?.completed?.length===1'),'Keep-both restore');
  const restored=await app.evaluate('recycleState.report.completed[0].destination');
  assert.notEqual(restored,file);assert.equal(fs.readFileSync(restored,'utf8'),'owned-recycle-ui-fixture');assert.equal(fs.readFileSync(file,'utf8'),'new-live-fixture');
  await app.screenshot('recycle-restored');
  await app.evaluate("closeRecycleBin();_lang='en';openRecycleBin()");
  assert.equal(await app.evaluate('document.querySelector("#recycle-title").textContent'),'Recycle Bin');await app.screenshot('recycle-english');
  await app.evaluate('closeRecycleBin()');assert.equal(await app.evaluate('!!document.getElementById("recycle-dialog")'),false);
  console.log('Recycle Bin UI artifacts:',app.artifactDir);
});
