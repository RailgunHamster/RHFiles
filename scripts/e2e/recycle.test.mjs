import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import {launchApp,until} from '../testing/app-session.mjs';

test('Windows Recycle Bin UI uses real owned IDs and preserves user data',{timeout:120000},async t=>{
  const app=await launchApp({emulateFocus:true});await app.evaluate("setLang('zh');setInspectorMode('closed',false);true");
  const invoke=(name,args={})=>app.evaluate(`call(${JSON.stringify(name)},${JSON.stringify(args)})`);
  const directory=fs.realpathSync.native(app.directory),file=path.join(directory,'回收站 QA #.txt');
  fs.writeFileSync(file,'owned-recycle-ui-fixture');
  await invoke('delete_file',{path:file});
  t.after(async()=>{try{const bin=await invoke('recycle_bin_list');const owned=bin.items.filter(e=>e.originalPath.toLowerCase()===file.toLowerCase());if(owned.length)await invoke('recycle_bin_restore',{ids:owned.map(e=>e.id),policy:'keepBoth',operationId:'qa-recycle-cleanup'});}finally{app.close();}});
  await app.click('#sidebar-recycle');
  await until(()=>app.evaluate('getTab().path==="recycle://"&&!recycleModel().loading'),'Recycle Bin loaded');
  assert.equal(await app.evaluate('!!document.querySelector(".recycle-browser")&&!document.querySelector("#recycle-dialog")'),true,'Recycle Bin is an ordinary tab, never a modal');
  const bin=await invoke('recycle_bin_list'),owned=bin.items.find(e=>e.originalPath===file);assert.ok(owned,'Owned fixture appears with its real original name');
  await app.evaluate(`recycleSetQuery(${JSON.stringify(path.basename(directory)+' 回收站 QA')});recycleSetSort('name',false);true`);
  assert.equal(await app.evaluate('document.querySelectorAll(".recycle-row").length'),1);
  await app.click(`[data-recycle-id="${owned.id}"]`);
  assert.deepEqual(await app.evaluate('recycleSelectedIds()'),[owned.id]);
  await app.evaluate(`toggleDualPane(true);true`);
  await until(()=>app.evaluate('G.rp.path==="recycle://"&&!recycleModel(G.rp).loading'),'Right Recycle Bin loaded');
  await app.evaluate("recycleSetQuery('right pane has no matches',G.rp);true");
  assert.equal(await app.evaluate('G.rp.entries.length'),0);
  assert.equal(await app.evaluate('getTab().entries.length'),1,'Right-pane filter never changes the left listing');
  await app.evaluate(`rpNavigateTo(${JSON.stringify(directory)})`);
  assert.equal(await app.evaluate('document.querySelector("#pane-right .file-header").classList.contains("recycle-location-header")'),false,'Ordinary folder headers return after leaving the bin');
  await app.screenshot('recycle-dual-pane');
  await app.evaluate('toggleDualPane(false);true');
  await app.evaluate('window.__originalBin=getTab();duplicateTab(getTab().id,false)');
  await until(()=>app.evaluate('!recycleModel().loading'),'Duplicated Recycle Bin loaded');
  await app.evaluate("recycleSetQuery('no matching fixture');true");
  assert.equal(await app.evaluate('getTab().entries.length'),0);
  await app.evaluate('switchTab(window.__originalBin.id);true');
  await until(()=>app.evaluate('!recycleModel().loading'),'Original Recycle Bin reloaded');
  assert.match(await app.evaluate('recycleModel().query'),/回收站 QA/,'Tab filters remain independent');
  await app.evaluate('goBack()');assert.equal(await app.evaluate('isRecyclePath(getTab().path)'),false);
  await app.evaluate('goForward()');assert.equal(await app.evaluate('getTab().path'),'recycle://');
  await app.evaluate(`recycleSetSelection([${JSON.stringify(owned.id)}]);true`);
  await app.evaluate("G.lastActivePane='left';toggleSort();true");
  assert.equal(await app.evaluate('recycleModel().sort'),'deletedAt','Toolbar sort uses the virtual listing model');
  await app.screenshot('recycle-light-zh');
  await app.evaluate("applyTheme('dark',false);true");await app.screenshot('recycle-dark-zh');
  await app.evaluate("applyTheme('light',false);true");
  await app.send('Emulation.setDeviceMetricsOverride',{width:740,height:600,deviceScaleFactor:1,mobile:false});
  assert.equal(await app.evaluate('document.querySelector("[data-recycle-control=empty]").getBoundingClientRect().right<=innerWidth'),true);
  await app.screenshot('recycle-narrow-zh');await app.send('Emulation.clearDeviceMetricsOverride');
  await app.click('[data-recycle-control=remove]');
  await until(()=>app.evaluate('!!document.querySelector(".app-confirm-overlay")'),'First permanent-delete confirmation');
  await app.click('.app-confirm-overlay .dialog-actions button:last-child');
  await until(()=>app.evaluate('document.querySelector(".app-confirm-overlay .app-confirm-title")?.textContent===recycleText("finalTitle")'),'Second permanent-delete confirmation');
  await app.click('.app-confirm-overlay .dialog-actions button:first-child');
  await until(()=>app.evaluate('!recycleBusy'),'Delete cancelled');
  assert.ok((await invoke('recycle_bin_list')).items.some(e=>e.id===owned.id),'Cancel leaves recycled item intact');
  fs.writeFileSync(file,'new-live-fixture');
  await app.click('[data-recycle-control=restore]');
  await until(()=>app.evaluate('!recycleBusy&&!!recycleModel().report'),'Restore conflict report');
  assert.equal(await app.evaluate('recycleModel().report.skipped[0].code'),'conflict');assert.equal(fs.readFileSync(file,'utf8'),'new-live-fixture');
  await app.click('[data-recycle-control=keep]');
  await until(()=>app.evaluate('!recycleBusy&&recycleModel().report?.completed?.length===1'),'Keep-both restore');
  const restored=await app.evaluate('recycleModel().report.completed[0].destination');
  assert.notEqual(restored,file);assert.equal(fs.readFileSync(restored,'utf8'),'owned-recycle-ui-fixture');assert.equal(fs.readFileSync(file,'utf8'),'new-live-fixture');
  await app.screenshot('recycle-restored');
  await app.evaluate(`(()=>{const pane=getTab(),state=recycleModel(pane);state.items=Array.from({length:50000},(_,i)=>({id:'synthetic-'+i,name:'Synthetic '+i,originalPath:'C:/Fixture/'+i,originalFolder:'C:/Fixture',size:i,deletedAt:i}));state.total=state.items.length;state.query='';state.sort='name';state.descending=false;G.layout='cards';recycleRebuild(pane,[]);recyclePaint(pane);moveFileSelectionByArrow('ArrowDown');moveFileSelectionByArrow('ArrowDown',{extend:true});return true})()`);
  assert.equal(await app.evaluate('getTab().sel.size'),2,'Shift+Down extends selection even when the normal layout is Cards');
  await app.evaluate('ACTION_HANDLERS["nav.end"]()');
  assert.equal(await app.evaluate('getTab().lastIdx'),49999);
  assert.equal(await app.evaluate('document.querySelectorAll(".recycle-row").length<=200'),true,'Large bins keep the DOM bounded');
  assert.equal(await app.evaluate(`(()=>{const list=document.getElementById('file-list'),row=list.querySelector('[data-index="49999"]'),a=list.getBoundingClientRect(),b=row.getBoundingClientRect();return b.top>=a.top&&b.bottom<=a.bottom})()`),true,'End scrolls to the actual visible recycled row');
  await app.evaluate("G.layout='details';true");
  await app.evaluate("closeRecycleBin();setLang('en');openRecycleBin()");
  assert.equal(await app.evaluate('tabName(getTab().path)'),'Recycle Bin');await app.screenshot('recycle-english');
  await app.evaluate('closeRecycleBin()');
  assert.equal(await app.evaluate('document.querySelectorAll("#recycle-dialog").length'),0);
  console.log('Recycle Bin UI artifacts:',app.artifactDir);
});
