# Restores the hand-maintained Android inputs that `cargo tauri android init`
# regenerates from a template, and guarantees a signing key exists.
#
#   pwsh -File scripts/android-sync.ps1
#
# Run this after `cargo tauri android init`, and before any build (it is cheap and
# idempotent). It:
#   1. creates the shared signing keystore on first use,
#   2. writes keystore.properties into the generated Gradle project,
#   3. restores android/gradle/app/build.gradle.kts (one signing key for both
#      debug and release, so an update never needs an uninstall),
#   4. restores android/manifest/AndroidManifest.xml (permissions).

param(
    [string]$Keystore
)

$ErrorActionPreference = 'Stop'

$repoRoot = Split-Path -Parent $PSScriptRoot
$generatedRoot = Join-Path $repoRoot 'android\src-tauri\gen\android'

if (-not (Test-Path $generatedRoot)) {
    throw "the Android project has not been generated yet. Run 'cargo tauri android init' in android/ first."
}

# --- 1. signing key ---------------------------------------------------------

$javaHome = @(
    $env:JAVA_HOME,
    'C:\Program Files\Microsoft\jdk-21.0.12.101-hotspot'
) | Where-Object { $_ -and (Test-Path (Join-Path $_ 'bin\keytool.exe')) } | Select-Object -First 1
if (-not $javaHome) {
    throw 'no JDK with keytool found; set JAVA_HOME to a JDK 17+ installation'
}
$env:JAVA_HOME = $javaHome

if (-not $Keystore) {
    $Keystore = Join-Path $env:USERPROFILE '.android\rhfiles-debug.keystore'
}
if (-not (Test-Path $Keystore)) {
    Write-Host "creating shared signing keystore: $Keystore"
    New-Item -ItemType Directory -Force -Path (Split-Path -Parent $Keystore) | Out-Null
    & (Join-Path $javaHome 'bin\keytool.exe') -genkeypair -v -keystore $Keystore `
        -storepass android -keypass android -alias rhfiles -keyalg RSA -keysize 2048 `
        -validity 10000 -dname 'CN=RHFiles Debug,O=RHFiles,C=CN' | Out-Null
} else {
    Write-Host "using signing keystore: $Keystore"
}

# --- 2. keystore.properties -------------------------------------------------

$propertiesPath = Join-Path $generatedRoot 'keystore.properties'
$properties = @(
    "# Generated by scripts/android-sync.ps1 — do not edit the generated copy.",
    "storeFile=$($Keystore -replace '\\', '/')",
    'storePassword=android',
    'keyAlias=rhfiles',
    'keyPassword=android'
) -join "`n"
if ((Test-Path $propertiesPath) -and ((Get-Content $propertiesPath -Raw).Trim() -ceq $properties.Trim())) {
    Write-Host "already in sync: $propertiesPath"
} else {
    Set-Content -Path $propertiesPath -Value $properties -NoNewline
    Write-Host "updated: $propertiesPath"
}

# --- 3. and 4. files that the template gets wrong or must not own -----------

function Sync-File {
    param([string]$Source, [string]$Target)

    if (-not (Test-Path $Source)) { throw "missing source file: $Source" }
    if (-not (Test-Path (Split-Path -Parent $Target))) {
        throw "missing target directory: $(Split-Path -Parent $Target)"
    }

    $desired = (Get-Content $Source -Raw)
    if ((Test-Path $Target) -and ((Get-Content $Target -Raw) -ceq $desired)) {
        Write-Host "already in sync: $Target"
        return
    }
    Copy-Item $Source $Target -Force
    Write-Host "updated: $Target"
}

$appDir = Join-Path $generatedRoot 'app'
$testManifest=Join-Path $repoRoot 'android\gradle\app\src\androidTest\AndroidManifest.xml'
if(Test-Path -LiteralPath $testManifest){New-Item -ItemType Directory -Path (Join-Path $appDir 'src\androidTest') -Force | Out-Null;Sync-File -Source $testManifest -Target (Join-Path $appDir 'src\androidTest\AndroidManifest.xml')}
Sync-File -Source (Join-Path $repoRoot 'android\gradle\build.gradle.kts') -Target (Join-Path $generatedRoot 'build.gradle.kts')
Sync-File `
    -Source (Join-Path $repoRoot 'android\gradle\app\proguard-rules.pro') `
    -Target (Join-Path $appDir 'proguard-rules.pro')
Sync-File `
    -Source (Join-Path $repoRoot 'android\gradle\app\build.gradle.kts') `
    -Target (Join-Path $appDir 'build.gradle.kts')

# Restore the origin-restricted Android integration and file-sharing roots.
Sync-File `
    -Source (Join-Path $repoRoot 'android\manifest\file_paths.xml') `
    -Target (Join-Path $appDir 'src\main\res\xml\file_paths.xml')

# Launcher bitmaps and adaptive/round resources are canonical inputs too. Updating
# src-tauri/icons alone does not replace the generated Gradle launcher's resources.
$resourceSource = Join-Path $repoRoot 'android\gradle\app\src\main\res'
$resourceTarget = Join-Path $appDir 'src\main\res'
foreach ($resource in Get-ChildItem -LiteralPath $resourceSource -Recurse -File) {
    $relative = [IO.Path]::GetRelativePath($resourceSource, $resource.FullName)
    $target = Join-Path $resourceTarget $relative
    New-Item -ItemType Directory -Path (Split-Path -Parent $target) -Force | Out-Null
    if (-not (Test-Path -LiteralPath $target) -or
        (Get-FileHash -LiteralPath $target -Algorithm SHA256).Hash -ne (Get-FileHash -LiteralPath $resource.FullName -Algorithm SHA256).Hash) {
        Copy-Item -LiteralPath $resource.FullName -Destination $target
        Write-Host "updated resource: $relative"
    }
}

Sync-File `
    -Source (Join-Path $repoRoot 'android\gradle\app\src\main\java\com\railgunhamster\rhfiles\MainActivity.kt') `
    -Target (Join-Path $appDir 'src\main\java\com\railgunhamster\rhfiles\MainActivity.kt')

# New native modules and JVM business tests are canonical inputs too.
# Remove only this retired generated source; copying new inputs alone would
# silently retain the obsolete independent-pairing Activity in existing builds.
$retiredScanner = Join-Path $appDir 'src\main\java\com\railgunhamster\rhfiles\PairingScanActivity.kt'
if (Test-Path -LiteralPath $retiredScanner) { Remove-Item -LiteralPath $retiredScanner -Force }
foreach ($sourceSet in @('main', 'test', 'androidTest')) {
    $canonical = Join-Path $repoRoot "android\gradle\app\src\$sourceSet\java\com\railgunhamster\rhfiles"
    $destination = Join-Path $appDir "src\$sourceSet\java\com\railgunhamster\rhfiles"
    if (Test-Path $canonical) {
        New-Item -ItemType Directory -Force -Path $destination | Out-Null
        foreach ($source in Get-ChildItem -LiteralPath $canonical -File | Where-Object Extension -In @('.kt','.java')) {
            Sync-File -Source $source.FullName -Target (Join-Path $destination $source.Name)
        }
    }
}

$targets = Get-ChildItem $generatedRoot -Recurse -File -Filter 'AndroidManifest.xml' |
    Where-Object { $_.FullName -notlike '*\build\*' -and $_.FullName -notlike '*\src\androidTest\*' }
if (-not $targets) {
    throw "no AndroidManifest.xml found under $generatedRoot"
}
foreach ($target in $targets) {
    Sync-File `
        -Source (Join-Path $repoRoot 'android\manifest\AndroidManifest.xml') `
        -Target $target.FullName
}

Write-Host 'Android project sync complete.'
# RHVideo uses the same packaged library UI, with a phone-specific bridge and
# layout. Copy only these allowlisted assets, never the desktop file browser.
$rhvideoAssets=Join-Path $appDir 'src/main/assets/rhvideo'
foreach($relative in @('rhvideo.html','rhvideo-operations.json','css/rhvideo.css','css/rhvideo-workbench.css','js/automation-core.js','js/rhvideo-model.js','js/rhvideo-client.js','js/rhvideo-configuration.js','js/rhvideo-exports.js','js/rhvideo-duplicates.js','js/rhvideo-task-priority.js','js/rhvideo-rules-model.js','js/rhvideo-rules.js','js/rhvideo-workbench.js','js/rhvideo-index.js','js/rhvideo-refresh.js','js/rhvideo-worker.js','js/rhvideo-search.js','js/rhvideo-tags.js','vendor/pinyin-pro/pinyin-pro.js','vendor/pinyin-pro/LICENSE','vendor/pinyin-pro/PROVENANCE.txt','vendor/rhvideo/LICENSE')){
    $destination=Join-Path $rhvideoAssets $relative
    New-Item -ItemType Directory -Force -Path (Split-Path -Parent $destination) | Out-Null
    Sync-File -Source (Join-Path $repoRoot ('src/'+$relative)) -Target $destination
}
foreach($relative in @('css/rhvideo-mobile.css','js/rhvideo-mobile.js')){
    Sync-File -Source (Join-Path $repoRoot ('android/web/'+$relative)) -Target (Join-Path $rhvideoAssets $relative)
}
Sync-File -Source (Join-Path $repoRoot 'src\js\nearby-ui.js') -Target (Join-Path $repoRoot 'android\web\js\nearby-ui.js')
Sync-File -Source (Join-Path $repoRoot 'src\js\device-groups-ui.js') -Target (Join-Path $repoRoot 'android\web\js\device-groups-ui.js')
Sync-File -Source (Join-Path $repoRoot 'src\css\device-groups.css') -Target (Join-Path $repoRoot 'android\web\css\device-groups.css')
Sync-File -Source (Join-Path $repoRoot 'src\js\automation-core.js') -Target (Join-Path $repoRoot 'android\web\js\automation-core.js')
# Include the unmodified project license and source attribution in every APK.
Sync-File -Source (Join-Path $repoRoot 'LICENSE') -Target (Join-Path $repoRoot 'android\web\LICENSE.txt')
Sync-File -Source (Join-Path $repoRoot 'NOTICE') -Target (Join-Path $repoRoot 'android\web\NOTICE.txt')
New-Item -ItemType Directory -Force -Path (Join-Path $repoRoot 'android\web\lan-service-licenses') | Out-Null
Get-ChildItem -LiteralPath (Join-Path $repoRoot 'docs\thirdparty\lan-service') -File | ForEach-Object {
    Sync-File -Source $_.FullName -Target (Join-Path $repoRoot ('android\web\lan-service-licenses\'+$_.Name))
}
$rhAndroidVersion=(Get-Content -LiteralPath (Join-Path $repoRoot 'android\src-tauri\tauri.conf.json') -Raw|ConvertFrom-Json).version
$rhAndroidNotes=Join-Path $repoRoot ('docs\release-notes\android\'+$rhAndroidVersion+'.md')
if(Test-Path -LiteralPath $rhAndroidNotes){
    # Versioned notes are reproducible without overwriting local draft notes.
    $rhHistory=Get-ChildItem -LiteralPath (Split-Path $rhAndroidNotes) -Filter '*.md' -File |
        Where-Object {$_.BaseName -match '^\d+\.\d+\.\d+$'} | Sort-Object {[version]$_.BaseName} -Descending |
        ForEach-Object {Get-Content -LiteralPath $_.FullName -Raw}
    [IO.File]::WriteAllText((Join-Path $repoRoot 'android\web\CHANGELOG.txt'),($rhHistory -join "`n`n"),[Text.UTF8Encoding]::new($false))
}else{
    Sync-File -Source (Join-Path $repoRoot 'android\release-notes.txt') -Target (Join-Path $repoRoot 'android\web\CHANGELOG.txt')
}
